-- 032: короткая подпись фигуры для схемы поля.
--
-- На схеме половины уже подписаны («База противника» / «Наша база»), поэтому
-- суффикс Б/Д на каждой из 46 кнопок дублирует эту информацию и перегружает
-- экран (Василий, 2026-07-31, по скриншоту staging). Половина поля остаётся
-- обязательной — она нужна, чтобы понимать, на чьей стороне игрока выбили, —
-- но живёт в `side`, а не в подписи кнопки.
--
-- Отдельная колонка, а не обрезка на клиенте: `code` — доменный идентификатор
-- («Z2Д» произносят на разборе), и отрезать от него хвост в вёрстке значит
-- размазать знание о схеме кодирования по фронтенду.

ALTER TABLE field_positions ADD COLUMN IF NOT EXISTS short_code TEXT;

UPDATE field_positions SET short_code = regexp_replace(code, '[БД]$', '');

ALTER TABLE field_positions ALTER COLUMN short_code SET NOT NULL;
