-- 028: справочник позиций (укрытий/фигур) на пейнтбольном поле.
-- Питает модуль рефлексии игрока (#89): где игрока выбили, откуда он отстрелил.
--
-- Модель — один плоский каталог в МАКСИМАЛЬНОЙ конфигурации: он содержит все
-- фигуры, которые вообще могут стоять на поле. Поле конкретной конфигурации —
-- это подмножество каталога (флаг active). Отдельной сущности «раскладка поля»
-- сознательно НЕТ: конфигураций мало, они не живут одновременно.
--
-- Три независимые группы фигур. Числа, змеи и конверты НЕ пересекаются:
-- «4-й конверт» — это 4-й конверт, а не «50». Группа входит в идентификатор,
-- поэтому совпадение номеров безопасно: grid.50 и envelope.4 не столкнутся.
--
--   grid      1..5 / 10..50 / 100..500 / 1000..5000   20 фигур
--   snake     1..4 (4 змеи — заложен максимум)          4 фигуры
--   envelope  1..4 (бывают поля с 4 конвертами)         4 фигуры
--                                              итого = 28 фигур
--
-- Фигура существует либо на обеих половинах — Б (NEAR, наша) и Д (FAR,
-- противника), — либо на центральной линии в единственном экземпляре (CENTER).
-- Центральный ТОЛЬКО тысячный числовой ряд 1000..5000: он стоит ровно на
-- середине поля и не дублируется, «нашей 3000» и «их 3000» не бывает.
-- Z4/K4 при этом остаются сторонними: на глубинной линии своей половины
-- стоят только фланговые фигуры, числовой ряд там уже общий.
-- NEAR/FAR — та же номенклатура, что в event_games.pit_zone.
--
--   1..500      15 фигур x 2 стороны = 30
--   1000..5000   5 фигур x центр     =  5
--   snake 1..4   4 фигуры x 2 стороны =  8
--   envelope 1..4 4 фигуры x 2 стороны = 8
--                                 итого = 51 позиция
--
-- Фланга у фигуры НЕТ сознательно: у числовой фигуры линия (змеиная/центр/
-- конвертная) зависит от раскладки конкретного поля, а не от самой фигуры,
-- поэтому в статическом каталоге ей не место. У змей и конвертов фланг
-- выводится из figure_group и хранить его отдельно — дубль.
--
-- Алиасов тоже нет: выбор позиции — это тап по схеме поля, клавиатура не
-- открывается. Разговорные формы понадобятся только на задаче парсинга
-- транскриптов разборов — тогда и добавим отдельной миграцией.
--
-- Раскладка схемы. Глубина растёт от своей базы, поэтому половина противника
-- зеркальна по вертикали. Тысячный ряд рисуется один раз, на центре:
--
--                    БАЗА ПРОТИВНИКА
--   Z1Д |    1    2    3    4    5 | K1Д
--   Z2Д |   10   20   30   40   50 | K2Д
--   Z3Д |  100  200  300  400  500 | K3Д
--   Z4Д |                          | K4Д
--   ----- 1000 2000 3000 4000 5000 -----  центральная линия
--   Z4Б |                          | K4Б
--   Z3Б |  100  200  300  400  500 | K3Б
--   Z2Б |   10   20   30   40   50 | K2Б
--   Z1Б |    1    2    3    4    5 | K1Б
--                      НАША БАЗА
--
-- Змея/конверты меняются местами тапом в UI (зависит от базы, с которой
-- играем) — это чисто визуально, id фигуры от перестановки не зависит.
--
-- Спека: vault 02_PROJECTS/Paintball TeamHub/06_specs/
--        player_reflection_analytics_v1_2026_07_12_telegram.md (§7)

CREATE TABLE IF NOT EXISTS field_positions (
  id           TEXT PRIMARY KEY,           -- grid.3000.center | snake.2.far | envelope.4.near
  figure_group TEXT NOT NULL,              -- grid | snake | envelope (расширяемо)
  figure_index TEXT NOT NULL,              -- 3000 | 2 | 4
  side         TEXT NOT NULL,              -- NEAR (наша) | FAR (противника) | CENTER (общая)
  code         TEXT NOT NULL,              -- подпись на кнопке: 3000 | Z2Д | K4Б
  depth        SMALLINT NOT NULL,          -- ряд схемы: 1 | 10 | 100 | 1000, растёт от базы
  label        TEXT NOT NULL,              -- «3000», «4-й конверт Д»
  active       BOOLEAN NOT NULL DEFAULT TRUE, -- стоит ли фигура на текущем поле
  sort_order   INTEGER NOT NULL,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  CONSTRAINT field_positions_group_check CHECK (figure_group IN ('grid', 'snake', 'envelope')),
  CONSTRAINT field_positions_side_check  CHECK (side IN ('NEAR', 'FAR', 'CENTER'))
);

CREATE UNIQUE INDEX IF NOT EXISTS field_positions_figure_side_uniq
  ON field_positions (figure_group, figure_index, side);

CREATE UNIQUE INDEX IF NOT EXISTS field_positions_code_uniq ON field_positions (code);

CREATE INDEX IF NOT EXISTS field_positions_active_idx ON field_positions (active) WHERE active;

-- Сид каталога. Фигура перечислена один раз, стороны разворачиваются LATERAL:
-- центральная даёт одну строку (CENTER), сторонняя — две (NEAR + FAR).
INSERT INTO field_positions (id, figure_group, figure_index, side, code, depth, label, sort_order)
SELECT
  f.grp || '.' || f.idx || '.' || lower(s.side),
  f.grp,
  f.idx,
  s.side,
  f.code || s.suffix,
  f.depth,
  f.label || s.label_suffix,
  f.ord * 10 + s.ord
FROM (VALUES
  -- числовая сетка: разряд = линия глубины, код = само число.
  -- Тысячный ряд центральный (central = TRUE) — см. шапку миграции.
  ('grid', '1',    '1',    1::SMALLINT, '1',    FALSE,  1),
  ('grid', '2',    '2',    1,           '2',    FALSE,  2),
  ('grid', '3',    '3',    1,           '3',    FALSE,  3),
  ('grid', '4',    '4',    1,           '4',    FALSE,  4),
  ('grid', '5',    '5',    1,           '5',    FALSE,  5),
  ('grid', '10',   '10',   10,          '10',   FALSE,  6),
  ('grid', '20',   '20',   10,          '20',   FALSE,  7),
  ('grid', '30',   '30',   10,          '30',   FALSE,  8),
  ('grid', '40',   '40',   10,          '40',   FALSE,  9),
  ('grid', '50',   '50',   10,          '50',   FALSE, 10),
  ('grid', '100',  '100',  100,         '100',  FALSE, 11),
  ('grid', '200',  '200',  100,         '200',  FALSE, 12),
  ('grid', '300',  '300',  100,         '300',  FALSE, 13),
  ('grid', '400',  '400',  100,         '400',  FALSE, 14),
  ('grid', '500',  '500',  100,         '500',  FALSE, 15),
  ('grid', '1000', '1000', 1000,        '1000', TRUE,  16),
  ('grid', '2000', '2000', 1000,        '2000', TRUE,  17),
  ('grid', '3000', '3000', 1000,        '3000', TRUE,  18),
  ('grid', '4000', '4000', 1000,        '4000', TRUE,  19),
  ('grid', '5000', '5000', 1000,        '5000', TRUE,  20),
  -- Змеи и конверты стоят на флангах и растут от базы вглубь: Z1/K1 — начало,
  -- Z4/K4 — дальняя линия своей половины. Центральными НЕ являются: на глубинной
  -- линии половины стоят только фланговые фигуры, числовой ряд там уже общий.
  -- depth задаёт ТОЛЬКО номер ряда схемы, это не отождествление: Z4 ≠ 4000.
  ('snake', '1', 'Z1', 1,    '1-я змея', FALSE, 21),
  ('snake', '2', 'Z2', 10,   '2-я змея', FALSE, 22),
  ('snake', '3', 'Z3', 100,  '3-я змея', FALSE, 23),
  ('snake', '4', 'Z4', 1000, '4-я змея', FALSE, 24),
  ('envelope', '1', 'K1', 1,    '1-й конверт', FALSE, 25),
  ('envelope', '2', 'K2', 10,   '2-й конверт', FALSE, 26),
  ('envelope', '3', 'K3', 100,  '3-й конверт', FALSE, 27),
  ('envelope', '4', 'K4', 1000, '4-й конверт', FALSE, 28)
) AS f(grp, idx, code, depth, label, central, ord)
CROSS JOIN LATERAL (
  SELECT v.side, v.suffix, v.label_suffix, v.ord
  FROM (VALUES
    ('NEAR',   'Б', ' Б', 1),
    ('FAR',    'Д', ' Д', 2),
    ('CENTER', '',  '',   3)
  ) AS v(side, suffix, label_suffix, ord)
  WHERE (v.side = 'CENTER') = f.central
) AS s
ON CONFLICT DO NOTHING;
