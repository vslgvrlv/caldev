import { Role } from '../types';

// «Сбор по событию» спрятан у всех (решение Василия 10.11.2026, п. 9).
//
// Что было не так: расход, внесённый в событии, списывался из казны, но в самом
// событии не появлялся («Потрачено 0 ₽»), а кнопка сбора оставалась
// заблокированной навсегда. Экран обещал то, чего сервер не делает.
//
// Код листов и ручки остаются на месте, данные не трогаем: сбор переделают
// вторым заходом, и начинать будут отсюда. Включить обратно — одна строка.
export const EVENT_COLLECTION_ENABLED = false;

export function canShowEventCollection(role: Role, enabled: boolean = EVENT_COLLECTION_ENABLED): boolean {
  if (!enabled) return false;
  // Игроку финансы события закрыты и после возвращения блока: ручки сервера
  // отвечают ему отказом.
  return role !== Role.PLAYER;
}
