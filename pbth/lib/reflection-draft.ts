// Черновик рефлексии (#105, слой 4). Очередь отправки спасает уже нажатое
// «Сохранить». А до нажатия форма живёт только в React-стейте: между играми
// человек убирает телефон в карман, iOS выгружает вкладку — и заполненное
// исчезает без единого следа. Поэтому черновик пишется на диск по каждому
// изменению и поднимается при следующем открытии той же формы.

import type { Snapshot } from './offline';

export function reflectionDraftKey(pointId: number | string): string {
  return `draft:reflection:${pointId}`;
}

// Турнир — это один день. Черновик, пролежавший дольше, скорее всего остался от
// прошлого выезда: поднимать его поверх сохранённой рефлексии — значит подсунуть
// человеку чужой пойнт и получить мусор в аналитике.
export const DRAFT_TTL_MS = 24 * 60 * 60 * 1000;

// Локальный черновик побеждает сохранённую версию, потому что он единственный
// нигде не сохранён: это работа, которую ещё никто не видел. Сохранённая копия
// уже лежит на сервере и не пропадёт, если её на минуту перекрыть.
export function chooseReflectionDraft<T>(local: Snapshot<T> | null, saved: T | null, now: number): T | null {
  if (!local) return saved;
  if (now - local.savedAt > DRAFT_TTL_MS) return saved;
  return local.value;
}
